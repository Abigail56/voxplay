// Lists the artwork that exists under public/images/voxplay/ into lib/art.available.ts.
// Runs before every build and dev server (npm "prebuild"/"predev"), so the site only ever
// references images that are really there; every other slot shows its drawn SVG scene.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "public", "images", "voxplay");
const found = [];
const walk = (d) => {
  if (!fs.existsSync(d)) return;
  for (const entry of fs.readdirSync(d, { withFileTypes: true })) {
    const full = path.join(d, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (/\.(webp|avif|jpe?g|png)$/i.test(entry.name)) found.push("/" + path.relative(path.join(root, "public"), full).split(path.sep).join("/"));
  }
};
walk(dir);
found.sort();
const out = `// Generated by scripts/scan-art.mjs: the artwork files in public/images/voxplay/. Don't edit by hand.\nexport const AVAILABLE_ART: readonly string[] = ${JSON.stringify(found, null, 2)};\n`;
fs.writeFileSync(path.join(root, "lib", "art.available.ts"), out);
console.log(`art: ${found.length} image${found.length === 1 ? "" : "s"} found in public/images/voxplay`);
